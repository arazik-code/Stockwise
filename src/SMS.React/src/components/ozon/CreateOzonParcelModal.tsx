import { useState, useEffect, useRef } from 'react'
import { Check, Search } from 'lucide-react'
import { ozonApi, ozonDeliveryNotePdfUrl, type OzonCity, type OzonParcel } from '../../api/ozon'
import { showToast } from '../shared/Toast'
import { formatCurrency } from '../../utils/format'
import { Button, Checkbox, Input, Modal, Textarea } from '../ui'

interface Prefill {
  onlineOrderId?: number
  receiver?: string
  phone?: string
  address?: string
  price?: number
  cityName?: string
}

export default function CreateOzonParcelModal({ prefill, onClose, onCreated }: {
  prefill?: Prefill
  onClose: () => void
  onCreated: (parcel: OzonParcel) => void
}) {
  const [receiver, setReceiver] = useState(prefill?.receiver ?? '')
  const [phone, setPhone] = useState(prefill?.phone ?? '')
  const [address, setAddress] = useState(prefill?.address ?? '')
  const [price, setPrice] = useState(prefill?.price ?? 0)
  const [city, setCity] = useState<OzonCity | null>(null)
  const [note, setNote] = useState('')
  const [nature, setNature] = useState('')
  const [isStock, setIsStock] = useState(false)
  const [fragile, setFragile] = useState(false)
  const [allowOpen, setAllowOpen] = useState(true)
  const [submitting, setSubmitting] = useState(false)

  // City search
  const [cityQuery, setCityQuery] = useState(prefill?.cityName ?? '')
  const [cityResults, setCityResults] = useState<OzonCity[]>([])
  const [cityOpen, setCityOpen] = useState(false)
  const debounce = useRef<ReturnType<typeof setTimeout> | null>(null)

  useEffect(() => {
    if (debounce.current) clearTimeout(debounce.current)
    if (!cityQuery.trim() || city?.name === cityQuery) { setCityResults([]); return }
    debounce.current = setTimeout(() => {
      ozonApi.getCities(cityQuery.trim()).then((r) => setCityResults(r.slice(0, 20))).catch(() => {})
    }, 250)
    return () => { if (debounce.current) clearTimeout(debounce.current) }
  }, [cityQuery, city])

  const pickCity = (c: OzonCity) => { setCity(c); setCityQuery(c.name); setCityOpen(false); setCityResults([]) }

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!receiver.trim() || !phone.trim() || !address.trim()) { showToast('Nom, téléphone et adresse sont requis', 'error'); return }
    if (!city) { showToast('Sélectionnez une ville de destination', 'error'); return }
    setSubmitting(true)
    try {
      const result = await ozonApi.createParcel({
        onlineOrderId: prefill?.onlineOrderId,
        receiver, phone, cityId: city.id, address, price,
        isStock, note: note || undefined, nature: nature || undefined, fragile, allowOpen,
      })
      if (!result.ok || !result.parcel) { showToast(result.error ?? 'Échec de création du colis', 'error'); return }
      showToast(`Colis créé — suivi ${result.parcel.trackingNumber}`, 'success')
      // Open OzonExpress's own official Bon de Livraison PDF (generated by them right after confirmation).
      if (result.parcel.deliveryNoteRef) {
        window.open(ozonDeliveryNotePdfUrl(result.parcel.deliveryNoteRef), '_blank', 'noopener,noreferrer')
      }
      onCreated(result.parcel)
    } catch {
      showToast('Erreur lors de la création du colis', 'error')
    } finally {
      setSubmitting(false)
    }
  }

  return (
    /*
      closeOnEsc stays FALSE.
      This modal is also mounted INSIDE OnlineOrdersPage's order-detail sheet.
      Modal/Sheet each attach their own document-level keydown listener, and
      stopPropagation does not stop sibling listeners on the same node - so an
      Escape press with both open would close the sheet out from under a
      half-filled parcel form. Neither surface opts in.

      No `required` is added to any field either: validation lives in
      handleSubmit above, and a native constraint would change when the form
      submits. The asterisks are label text, exactly as before.
    */
    <Modal
      open
      onClose={onClose}
      size="lg"
      title="Nouveau colis OzonExpress"
      description={prefill?.onlineOrderId ? 'Depuis une commande en ligne' : undefined}
      footer={
        <>
          <Button variant="outline" size="sm" onClick={onClose}>Annuler</Button>
          <Button
            type="submit"
            form="ozon-parcel-form"
            size="sm"
            loading={submitting}
          >
            {submitting ? 'Création…' : 'Créer le colis'}
          </Button>
        </>
      }
    >
      <form id="ozon-parcel-form" onSubmit={handleSubmit} className="space-y-4">
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <Input
            label="Destinataire *"
            value={receiver}
            onChange={(e) => setReceiver(e.target.value)}
            size="sm"
          />
          <Input
            label="Téléphone *"
            value={phone}
            onChange={(e) => setPhone(e.target.value)}
            placeholder="06XXXXXXXX"
            size="sm"
            className="num"
          />
        </div>

        <div className="relative">
          <Input
            label="Ville de destination *"
            value={cityQuery}
            onChange={(e) => { setCityQuery(e.target.value); setCity(null); setCityOpen(true) }}
            onFocus={() => setCityOpen(true)}
            placeholder="Rechercher une ville..."
            leading={<Search />}
            size="sm"
            hint={
              city ? (
                <span className="inline-flex items-center gap-1 text-positive">
                  <Check className="h-3 w-3" aria-hidden="true" />
                  {city.name} — livraison <span className="num">{formatCurrency(city.deliveredPrice)}</span>
                  {' · retour '}
                  <span className="num">{formatCurrency(city.returnedPrice)}</span>
                </span>
              ) : undefined
            }
          />
          {cityOpen && cityResults.length > 0 && (
            <div className="absolute inset-x-0 top-full z-20 mt-1 max-h-52 overflow-y-auto rounded-card border border-border bg-surface shadow-e3">
              {cityResults.map((c) => (
                <button
                  key={c.id}
                  type="button"
                  onClick={() => pickCity(c)}
                  className="flex w-full items-center justify-between gap-3 px-3 py-2 text-left text-sm text-fg transition-colors duration-fast hover:bg-surface-2 focus-visible:bg-surface-2 focus-visible:outline-none"
                >
                  <span className="truncate">{c.name}</span>
                  <span className="num shrink-0 text-xs text-fg-subtle">{formatCurrency(c.deliveredPrice)}</span>
                </button>
              ))}
            </div>
          )}
        </div>

        <Input
          label="Adresse complète *"
          value={address}
          onChange={(e) => setAddress(e.target.value)}
          size="sm"
        />

        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <Input
            label="Prix à encaisser (COD, MAD)"
            type="number"
            min={0}
            step="0.01"
            value={price}
            onChange={(e) => setPrice(parseFloat(e.target.value) || 0)}
            size="sm"
            className="num"
          />
          <Input
            label="Nature du contenu"
            value={nature}
            onChange={(e) => setNature(e.target.value)}
            placeholder="ex: Chaussures"
            size="sm"
          />
        </div>

        <Textarea
          label="Note / instructions"
          value={note}
          onChange={(e) => setNote(e.target.value)}
          rows={2}
        />

        <div className="flex flex-wrap gap-x-6 gap-y-3 border-t border-border pt-4">
          <span title="Activez uniquement si vos produits sont stockés chez OzonExpress (nécessite des références produits). Sinon, ramassage depuis votre boutique.">
            <Checkbox
              label="Stock OzonExpress"
              checked={isStock}
              onChange={(e) => setIsStock(e.target.checked)}
            />
          </span>
          <Checkbox
            label="Autoriser l'ouverture"
            checked={allowOpen}
            onChange={(e) => setAllowOpen(e.target.checked)}
          />
          <Checkbox
            label="Fragile"
            checked={fragile}
            onChange={(e) => setFragile(e.target.checked)}
          />
        </div>
      </form>
    </Modal>
  )
}
